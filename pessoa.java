public class pessoa {
    int idade;
    String nome;
    String CPF;
    boolean vivo;

    void definir_idade(int idade_pessoa){
        idade = idade_pessoa;
    }
    void definir_nome(String nome) {
        this.nome = nome;
    }
    void definir_CPF(String CPF_pessoa) {
        CPF = CPF_pessoa;
    }
    void definir_vivo(boolean vivo_pessoa){
        vivo = vivo_pessoa;
    }

}
